export const FORMATION_NAMES = Object.keys(F);

/** 生成某阵型、某队的一整队位置（米）。客队做镜像。 */
export function formationPositions(
  name: string,
  pitchType: PitchType,
  team: Team,
): Vec[] {
  const list = F[name]?.[pitchType];
  if (!list || list.length === 0) return [];
  const { L, W } = PITCH_DIMS[pitchType];
  return list.map((p) =>
    team === 'home'
      ? { x: p.x * L, y: p.y * W }
      : { x: (1 - p.x) * L, y: (1 - p.y) * W },
  );
}

export function formationSize(name: string, pitchType: PitchType): number {
  return F[name]?.[pitchType]?.length ?? 0;
}
